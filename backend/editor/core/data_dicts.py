def _resolve_csv_dict_dir():
    candidates = []

    meipass = getattr(sys, "_MEIPASS", None)
    if meipass:
        candidates.append(os.path.join(meipass, "csv_dicts"))

    if getattr(sys, "frozen", False):
        candidates.append(os.path.join(os.path.dirname(sys.executable), "csv_dicts"))

    module_dir = os.path.dirname(os.path.abspath(__file__))
    candidates.append(os.path.join(module_dir, "csv_dicts"))

    # 包结构（editor/core/）下向上回溯，寻找项目根目录的 csv_dicts
    current = module_dir
    for _ in range(4):
        parent = os.path.dirname(current)
        if parent == current:
            break
        current = parent
        candidates.append(os.path.join(current, "csv_dicts"))

    seen = set()
    for candidate in candidates:
        norm_candidate = os.path.normpath(candidate)
        if norm_candidate in seen:
            continue
        seen.add(norm_candidate)
        if os.path.isdir(norm_candidate):
            return norm_candidate

    return candidates[-1]


CSV_DICT_DIR = _resolve_csv_dict_dir()


def load_csv_dict(dict_name):
    csv_path = os.path.join(CSV_DICT_DIR, f"{dict_name}.csv")
    result = {}
    if os.path.exists(csv_path):
        try:
            with open(csv_path, "r", encoding="utf-8") as f:
                reader = csv.reader(f)
                next(reader, None)
                for row in reader:
                    if len(row) >= 2:
                        result[row[0]] = row[1]
        except Exception as e:
            print(f"Warning: Failed to load CSV {csv_path}: {e}")
    return result


def load_csv_rows(dict_name):
    csv_path = os.path.join(CSV_DICT_DIR, f"{dict_name}.csv")
    result = []
    if os.path.exists(csv_path):
        try:
            with open(csv_path, "r", encoding="utf-8", newline="") as f:
                reader = csv.DictReader(f)
                for row in reader:
                    result.append({k: (v or "").strip() for k, v in row.items()})
        except Exception as e:
            print(f"Warning: Failed to load structured CSV {csv_path}: {e}")
    return result


