SECONDARY_VARIABLE_RE = re.compile(r"^(?:@[A-Z_]+@|[A-Z][A-Z0-9*]*)$")


def _normalize_scalar(value):
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return str(int(value)) if value.is_integer() else str(value)

    text = str(value).strip()
    try:
        number = float(text)
        return str(int(number)) if number.is_integer() else text
    except Exception:
        return text


def _is_numeric_token(token):
    return str(token).lstrip("-").replace(".", "", 1).isdigit()


def _is_variable_token(token):
    return bool(SECONDARY_VARIABLE_RE.fullmatch(str(token))) and not _is_numeric_token(token)


def _is_rest_token(token):
    text = str(token)
    return text.endswith("*") and _is_variable_token(text)


def _parse_template_parts(code):
    return [part.strip() for part in str(code).strip().strip("[]").split(",") if part.strip()]


def build_secondary_type_name_map(type_rows):
    result = {}
    for row in type_rows:
        type_id = row.get("id", "")
        if not type_id:
            continue
        result[type_id] = (
            row.get("json_name")
            or row.get("vb_name")
            or row.get("source_file")
            or type_id
        )
    return result


def build_secondary_type_source_map(type_rows):
    result = {}
    for row in type_rows:
        type_id = row.get("id", "")
        source_file = row.get("source_file", "")
        if type_id and source_file:
            result[type_id] = source_file
    return result


def build_secondary_template_index(entries, type_rows, secondary_rows):
    type_name_map = build_secondary_type_name_map(type_rows)
    type_source_map = build_secondary_type_source_map(type_rows)
    secondary_meta_map = {
        (row.get("primary_code", ""), row.get("secondary_code", "")): row
        for row in secondary_rows
    }
    rule_map = build_rule_map(entries)

    by_signature = defaultdict(list)
    by_primary = defaultdict(list)

    for entry in entries:
        parts = _parse_template_parts(entry.get("code", ""))
        if len(parts) < 2 or not _is_numeric_token(parts[0]) or not _is_numeric_token(parts[1]):
            continue

        primary_code = _normalize_scalar(parts[0])
        secondary_code = _normalize_scalar(parts[1])
        meta = secondary_meta_map.get((primary_code, secondary_code), {})
        template = {
            "code": entry.get("code", ""),
            "desc": entry.get("desc", ""),
            "parts": parts,
            "primary_code": primary_code,
            "secondary_code": secondary_code,
            "primary_name": (
                meta.get("primary_name_json")
                or meta.get("primary_name_vb")
                or type_name_map.get(primary_code, primary_code)
            ),
            "source_file": meta.get("source_file", ""),
            "rule_mapping": rule_map.get(f"{primary_code}_{secondary_code}", {}),
        }
        by_signature[(primary_code, secondary_code)].append(template)
        by_primary[primary_code].append(template)

    for key in by_signature:
        by_signature[key].sort(key=lambda item: (-len(item["parts"]), item["code"]))
    for key in by_primary:
        by_primary[key].sort(key=lambda item: (item["secondary_code"], len(item["parts"]), item["code"]))

    return {
        "type_name_map": type_name_map,
        "type_source_map": type_source_map,
        "by_signature": dict(by_signature),
        "by_primary": dict(by_primary),
    }


def _template_allows_length(template, actual_length):
    parts = template.get("parts", [])
    if parts and _is_rest_token(parts[-1]):
        return actual_length >= len(parts)
    return len(parts) == actual_length


def _template_length_hint(template):
    parts = template.get("parts", [])
    if parts and _is_rest_token(parts[-1]):
        return f">= {len(parts)}"
    return str(len(parts))


def match_secondary_template(item_arr, template_index):
    if not isinstance(item_arr, list) or not item_arr:
        return {"status": "invalid_item"}
    if not isinstance(template_index, dict):
        return {"status": "missing_template_index"}

    primary_code = _normalize_scalar(item_arr[0])
    secondary_code = _normalize_scalar(item_arr[1]) if len(item_arr) > 1 else ""
    primary_templates = template_index["by_primary"].get(primary_code, [])
    if not primary_templates:
        if primary_code in template_index["type_name_map"]:
            return {
                "status": "known_primary_without_templates",
                "primary_code": primary_code,
                "secondary_code": secondary_code,
                "primary_name": template_index["type_name_map"].get(primary_code, primary_code),
                "source_file": template_index["type_source_map"].get(primary_code, ""),
            }
        return {
            "status": "unknown_primary",
            "primary_code": primary_code,
            "secondary_code": secondary_code,
            "primary_name": template_index["type_name_map"].get(primary_code, ""),
            "source_file": template_index["type_source_map"].get(primary_code, ""),
        }

    exact_templates = template_index["by_signature"].get((primary_code, secondary_code), [])
    if not exact_templates:
        return {
            "status": "unknown_secondary",
            "primary_code": primary_code,
            "secondary_code": secondary_code,
            "primary_name": template_index["type_name_map"].get(primary_code, primary_code),
            "source_file": template_index["type_source_map"].get(primary_code, ""),
            "known_secondary": sorted(
                {template["secondary_code"] for template in primary_templates},
                key=lambda value: (0, int(value)) if str(value).lstrip("-").isdigit() else (1, str(value)),
            ),
        }

    matched = []
    for template in exact_templates:
        if not _template_allows_length(template, len(item_arr)):
            continue

        params = {}
        fixed_matches = 0
        is_valid = True
        for idx, token in enumerate(template["parts"]):
            if _is_rest_token(token):
                params[token] = [_normalize_scalar(value) for value in item_arr[idx:]]
                break

            value = item_arr[idx]
            norm_value = _normalize_scalar(value)
            if _is_numeric_token(token):
                if norm_value != _normalize_scalar(token):
                    is_valid = False
                    break
                fixed_matches += 1
            else:
                params[token] = norm_value

        if is_valid:
            matched.append((fixed_matches, template, params))

    if matched:
        matched.sort(key=lambda item: (-item[0], -len(item[1]["parts"]), item[1]["code"]))
        _, template, params = matched[0]
        return {
            "status": "matched",
            "template": template,
            "params": params,
            "primary_code": primary_code,
            "secondary_code": secondary_code,
            }

    same_length = [template for template in exact_templates if _template_allows_length(template, len(item_arr))]
    if same_length:
        return {
            "status": "pattern_mismatch",
            "primary_code": primary_code,
            "secondary_code": secondary_code,
            "primary_name": template_index["type_name_map"].get(primary_code, primary_code),
        }

    return {
        "status": "arg_count_mismatch",
        "primary_code": primary_code,
        "secondary_code": secondary_code,
        "primary_name": template_index["type_name_map"].get(primary_code, primary_code),
        "expected_lengths": sorted({_template_length_hint(template) for template in exact_templates}),
        "actual_length": len(item_arr),
    }


def _lookup_secondary_name(expected_type, value, available_dicts):
    resolved_value = _normalize_scalar(value)
    dictionary = available_dicts.get(expected_type, {}) if available_dicts else {}

    if isinstance(dictionary, set):
        return resolved_value if resolved_value in dictionary else None

    return dictionary.get(resolved_value)


def render_secondary_template(template, params, available_dicts=None):
    desc = template["desc"]
    for token, value in params.items():
        if isinstance(value, list):
            desc = desc.replace(token, "[" + ", ".join(_normalize_scalar(item) for item in value) + "]")
            continue

        pretty_value = _normalize_scalar(value)
        if token in SECONDARY_PLACEHOLDER_MAP:
            expected_type, fallback_label = SECONDARY_PLACEHOLDER_MAP[token]
            resolved = _lookup_secondary_name(expected_type, pretty_value, available_dicts or {})
            desc = desc.replace(token, resolved or f"{fallback_label}({pretty_value})")
        elif _is_variable_token(token):
            desc = desc.replace(token, pretty_value)
    return desc


def validate_secondary_item(item_arr, template_index, available_dicts):
    if not isinstance(item_arr, list):
        return {"translation": str(item_arr), "errors": ["该行不是有效数组。"]}

    if len(item_arr) < 2:
        return {
            "translation": str(item_arr),
            "errors": ["每条二次代码至少需要 2 项，前两项必须是一级代码和二级代码。"],
        }

    primary_code = _normalize_scalar(item_arr[0])
    secondary_code = _normalize_scalar(item_arr[1])
    if not _is_numeric_token(primary_code):
        return {
            "translation": str(item_arr),
            "errors": [f"第 1 项 [{primary_code}] 不是有效的一级代码数字。"],
        }
    if not _is_numeric_token(secondary_code):
        return {
            "translation": str(item_arr),
            "errors": [f"第 2 项 [{secondary_code}] 不是有效的二级代码数字。"],
        }

    match_info = match_secondary_template(item_arr, template_index)
    if not isinstance(match_info, dict):
        return {
            "translation": f"[{', '.join(_normalize_scalar(x) for x in item_arr)}]",
            "errors": ["二次代码模板匹配器返回了无效结果。"],
        }

    status = match_info["status"]

    if status == "missing_template_index":
        return {
            "translation": f"[{', '.join(_normalize_scalar(x) for x in item_arr)}]",
            "errors": ["当前缺少二次代码模板索引，无法完成校验。"],
        }

    if status == "unknown_primary":
        return {
            "translation": f"[{', '.join(_normalize_scalar(x) for x in item_arr)}]",
            "errors": [f"一级代码 [{primary_code}] 不在二次代码字典中。"],
        }

    if status == "known_primary_without_templates":
        source_file = match_info.get("source_file", "")
        source_hint = f" 可参考源码 {source_file}。" if source_file else ""
        return {
            "translation": f"[{', '.join(_normalize_scalar(x) for x in item_arr)}]",
            "errors": [f"一级类型 [{match_info['primary_name']}] 已知，但当前模板库还没有收录它的二级代码定义。{source_hint}"],
        }

    if status == "unknown_secondary":
        known_secondary = match_info.get("known_secondary", [])
        hint = f"已知二级代码: {', '.join(known_secondary[:12])}" if known_secondary else "当前没有找到对应的二级模板。"
        source_file = match_info.get("source_file", "")
        if source_file:
            hint += f" 可参考源码 {source_file}。"
        return {
            "translation": f"[{', '.join(_normalize_scalar(x) for x in item_arr)}]",
            "errors": [f"{match_info['primary_name']} 的二级代码 [{secondary_code}] 不存在。{hint}"],
        }

    if status == "arg_count_mismatch":
        expected = " / ".join(str(length) for length in match_info.get("expected_lengths", []))
        return {
            "translation": f"[{', '.join(_normalize_scalar(x) for x in item_arr)}]",
            "errors": [f"{match_info['primary_name']} {secondary_code} 的参数数量不匹配，当前 {match_info['actual_length']} 项，常见模板需要 {expected} 项。"],
        }

    if status == "pattern_mismatch":
        return {
            "translation": f"[{', '.join(_normalize_scalar(x) for x in item_arr)}]",
            "errors": [f"{match_info['primary_name']} {secondary_code} 的固定参数不符合任何已知模板。"],
        }

    template = match_info["template"]
    params = match_info["params"]
    errors = []

    for idx, expected_type in template["rule_mapping"].items():
        if idx >= len(item_arr):
            continue

        value = _normalize_scalar(item_arr[idx])
        if not value or value in {"0", "-1"} or not _is_numeric_token(value):
            continue

        if _lookup_secondary_name(expected_type, value, available_dicts) is None:
            fallback_label = {
                "ROLE": "人物",
                "RELATION": "关系",
                "ATTR": "属性",
                "ITEM": "物品",
                "MAP": "地点",
                "JOB": "职业",
                "STATE": "状态",
                "TEXT": "文本",
                "NEGOTIATION_SKILL": "谈判技能",
                "NEGOTIATION_BUFF": "谈判Buff",
                "GAME": "游戏",
                "KZONE_POST": "空间动态",
                "KZONE_MESSAGE": "空间留言",
                "PHONE_MSG": "手机消息",
            }.get(expected_type, expected_type)
            errors.append(f"{fallback_label}ID [{value}] 字典中不存在。")

    translation = render_secondary_template(template, params, available_dicts)
    if template.get("primary_code") == "998":
        nested_effect = params.get("EFFECTS*")
        if isinstance(nested_effect, list) and nested_effect:
            nested_result = validate_secondary_item(
                nested_effect,
                EFFECT_SECONDARY_TEMPLATE_INDEX,
                available_dicts,
            )
            raw_nested = "[" + ", ".join(_normalize_scalar(item) for item in nested_effect) + "]"
            translation = translation.replace(raw_nested, nested_result["translation"], 1)
            errors.extend(f"嵌套效果 -> {error}" for error in nested_result["errors"])

    return {
        "translation": translation,
        "errors": errors,
        "template": template,
    }


